#!/usr/bin/env python3
"""The PLANT and the CONTROL MODEL must carry the same aircraft.

    python3 tests/test_tank_model_pairing.py

This is tank-plan phase 2's gate, and it is the one thing the plan insisted on:
the liquid goes into the plant and into `so3.M` IN THE SAME COMMIT, because the
reference is generated by solving a trim against the control model's mass. Get
them out of step and the reference stops being a trim -- the aircraft is then
tracking a package of (attitude, tilt, thrust) that does not balance, which is
exactly the failure that cost this project bags full_tr7, full_tr25 and full_tr27.

It is also the cross-repo contract test the extraction made necessary: the plant
lives here, the controller lives in fsc_autopilot_ros2, and nothing but this file
notices when they drift apart.

WHAT IS PINNED, and why it is not circular: `assembled_mass_properties` computes
the vehicle from the config's own links, and for the BASELINE airframe it
reproduces the controller's independently-derived constants exactly (M = 3.450,
CG_X = 0.1764, I = 0.265/0.303/0.490). That agreement is what makes it credible
for the tank case, where there is nothing to check against.

NOTE ON THE A/B: once this passes, the controller models the TANK aircraft. Flying
the baseline plant (`start_slosh_hil.sh --baseline`) against it means flying a
controller that believes in 0.5 kg of water that is not there. For a true baseline
run, check out the controller's `pre-slosh` tag.
"""
import ast
import numpy as np
import importlib.util
import os
import sys
import types
from unittest import mock

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from test_slosh_import import stub_isaac, load          # noqa: E402  (one stub harness)
sys.path.insert(0, os.path.join(HERE, ".."))
from controller_path import controller_dir              # noqa: E402

CTRL_HUB = os.path.join(controller_dir(), "px4_vtol_direct_actuator",
                        "nmpc_so3_transition_node.py")
# Every OTHER copy of the vehicle mass in the controller package. so3.M is the
# model hub, but the trim generator and the SAFE controller each carry their own,
# and the 2026-09-12 audit found the generator's still at 3.45 after so3.M moved:
# a 1.245 m/s^2 vertical residual in every baked reference -- the water, exactly.
# Since 2026-09-13 the water is SELECTABLE (VTOL_TANK_KG: 0.1 / 0.502 / 0.7 flown), so every
# copy is "airframe + the env var" with the SAME airframe constant, the SAME variable name and
# the SAME default -- that exact text is what is pinned, because a copy that reads a different
# name (or none) flies the wrong aircraft the moment the operator sets the variable.
AIRFRAME_M = 3.449572
ENV_PAT = r'3\.449572\s*\+\s*float\(os\.environ\.get\("VTOL_TANK_KG",\s*"0\.502"\)\s*or\s*0\.502\)'
OTHER_MASS_SITES = {
    "lib/fsc_transition_ref.py":  r"\bm=" + ENV_PAT,             # FSC = dict(m=..., ...)
    "geometric_hover_node.py":    r"self\.mass = " + ENV_PAT,    # safe controller default
    "vtol_nmpc.py":               r"^M = " + ENV_PAT,            # standalone node
}
TOL_M = 1e-3        # kg
TOL_CG = 1e-3       # m
TOL_I = 2e-3        # kg m^2


def controller_constants():
    """M, CG_X and the inertia diagonal, read from the controller's model hub.

    Parsed, not imported: importing it pulls casadi and builds solvers."""
    tree = ast.parse(open(CTRL_HUB).read())
    out = {}
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        # `IXX, IYY, IZZ = 0.265, 0.303, 0.490` is ONE assignment to a Tuple target,
        # not three Name targets -- miss that and the inertia silently reads as None.
        tgt = node.targets[0]
        if isinstance(tgt, ast.Tuple):
            targets = [e.id for e in tgt.elts if isinstance(e, ast.Name)]
        else:
            targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
        if isinstance(node.value, ast.Tuple):
            vals = [v.value for v in node.value.elts if isinstance(v, ast.Constant)]
            if len(targets) == len(vals):
                out.update(dict(zip(targets, vals)))
        elif isinstance(node.value, ast.Constant) and len(targets) == 1:
            out[targets[0]] = node.value.value
    return out


def main():
    bad = []
    stub_isaac()
    load("pegasus.simulator.logic.dynamics.vtol_aerodynamics", "dynamics/vtol_aerodynamics.py")
    slosh = load("pegasus.simulator.logic.dynamics.slosh", "dynamics/slosh.py")
    vtol = load("pegasus.simulator.logic.vehicles.vtol", "vehicles/vtol.py")
    vs = load("pegasus.simulator.logic.vehicles.vtol_slosh", "vehicles/vtol_slosh.py")

    cfg = vtol.quad_tiltrotor_config()
    m0, c0, i0 = vs.assembled_mass_properties(cfg)
    print(f"  plant, baseline airframe : M={m0:.3f} kg  CG=({c0[0]:.4f},{c0[1]:.4f},{c0[2]:.4f})  "
          f"I=({i0[0]:.3f},{i0[1]:.3f},{i0[2]:.3f})")

    # --- 1. the method is credible: it reproduces the controller's baseline ---
    for name, got, want, tol in (("M", m0, 3.450, TOL_M),
                                 ("CG_X", c0[0], 0.1764, TOL_CG),
                                 ("IXX", i0[0], 0.265, TOL_I),
                                 ("IYY", i0[1], 0.303, TOL_I),
                                 ("IZZ", i0[2], 0.490, TOL_I)):
        if abs(got - want) > tol:
            bad.append(f"baseline {name}: plant says {got:.4f}, the airframe's recorded "
                       f"value is {want} -- the assembly maths or the config changed")

    # --- 2. the tank aircraft ------------------------------------------------
    tank = slosh.default_tank()
    folded, before, after = vs.fold_tank_into_body(cfg, tank)
    m1, c1, i1 = after
    print(f"  plant, WITH the tank     : M={m1:.3f} kg  CG=({c1[0]:.4f},{c1[1]:.4f},{c1[2]:.4f})  "
          f"I=({i1[0]:.3f},{i1[1]:.3f},{i1[2]:.3f})")

    exp = m0 + slosh.slosh_parameters(tank).fluid_mass
    if abs(m1 - exp) > TOL_M:
        bad.append(f"folding the tank lost mass: {m1:.4f} vs {exp:.4f}")
    # mounted at the CG -> the CG must not move at all
    moved = max(abs(c1[k] - c0[k]) for k in range(3))
    if moved > 1e-9:
        bad.append(f"the default tank moved the CG by {1000 * moved:.3f} mm; mounted at the "
                   f"assembled CG it must not move it at all")
    if not all(i1[k] >= i0[k] for k in range(3)):
        bad.append("adding mass reduced an inertia")
    # the caller's config must not have been mutated
    if cfg.mass != 2.95:
        bad.append(f"fold_tank_into_body MUTATED the caller's config (mass now {cfg.mass})")

    # --- 3. THE PAIRING ------------------------------------------------------
    k = controller_constants()
    import re
    hub_src = open(CTRL_HUB).read()
    # since 2026-09-14 the hub's CG_X / IXX.. are DERIVED from the tank position (VTOL_TANK_DX/DZ);
    # the nominal constants are CG_X0 / IXX0.. and section 6 below checks the derivation
    ca_m = k.get("AIRFRAME_M"); ccg = k.get("CG_X0", k.get("CG_X"))
    ci = (k.get("IXX0", k.get("IXX")), k.get("IYY0", k.get("IYY")), k.get("IZZ0", k.get("IZZ")))
    env_ok = re.search(r'^TANK_KG = float\(os\.environ\.get\("VTOL_TANK_KG", "0\.502"\) or 0\.502\)\s*$'
                       r'\n^M = AIRFRAME_M \+ TANK_KG', hub_src, re.M) is not None
    cm = (ca_m + slosh.tank_kg_from_env()) if ca_m is not None else None
    print(f"  control model            : M={cm} kg (AIRFRAME_M {ca_m} + VTOL_TANK_KG)  CG_X={ccg}  I={ci}")
    if ca_m is None or ccg is None or None in ci:
        bad.append(f"could not read AIRFRAME_M/CG_X/I* from {CTRL_HUB}")
    elif not env_ok:
        bad.append(f"{os.path.basename(CTRL_HUB)} does not build M as AIRFRAME_M + TANK_KG from "
                   f"VTOL_TANK_KG (default 0.502) -- the plant reads that variable, the model must too")
    else:
        if abs(ca_m - m0) > TOL_M:
            bad.append(f"AIRFRAME MISMATCH: the plant's airframe assembles to {m0:.4f} kg, the control "
                       f"model's AIRFRAME_M is {ca_m}")
        if abs(cm - m1) > TOL_M:
            bad.append(f"MASS MISMATCH: the plant flies {m1:.3f} kg with the tank, the control "
                       f"model carries {cm} kg. Update M in {os.path.basename(CTRL_HUB)} "
                       f"(and expect a JIT rebuild -- the cache key hashes the model source). "
                       f"Until then the reference is not a trim.")
        if abs(ccg - c1[0]) > TOL_CG:
            bad.append(f"CG MISMATCH: plant {c1[0]:.4f} m, control model {ccg} m")
        for nm, got, want in zip(("IXX", "IYY", "IZZ"), ci, i1):
            if abs(got - want) > TOL_I:
                bad.append(f"{nm} MISMATCH: plant {want:.4f}, control model {got}")

    # --- 4. the other copies of the mass must read the SAME variable the same way ---------
    for rel, pat in OTHER_MASS_SITES.items():
        path = os.path.join(controller_dir(), "px4_vtol_direct_actuator", rel)
        src = open(path).read()
        hit = re.search(pat, src, re.M)
        tag = "ok" if hit else "MISMATCH"
        print(f"  {rel:28s} mass = 3.449572 + VTOL_TANK_KG   {tag}")
        if not hit:
            bad.append(f"{rel} does not carry the mass as 3.449572 + VTOL_TANK_KG (default 0.502) -- "
                       f"a stale or differently-wired copy (the trim generator's copy left a "
                       f"1.245 m/s^2 residual once)")

    # --- 4b. and so must the GROUND STATION's speed checks (stall 15.12 / 15.50, not 14.13) ---
    gs = os.path.expanduser("~/ros2_ws/src/ros2_ground_station_gui/src/ROS_Node/trajectory_player.py")
    if os.path.exists(gs):
        src = open(gs).read()
        hit = re.search(r"M_KG = 3\.449572 \+ WATER_KG", src) and re.search(
            r'WATER_KG = float\(os\.environ\.get\("VTOL_TANK_KG", "0\.502"\) or 0\.502\)', src)
        print(f"  {'GS trajectory_player.py':28s} mass = 3.449572 + VTOL_TANK_KG   {'ok' if hit else 'MISMATCH'}")
        if not hit:
            bad.append("the ground station's speed checks do not carry the mass as 3.449572 + "
                       "VTOL_TANK_KG (default 0.502): it would quote the baseline 14.13 m/s stall "
                       "for an aircraft that stalls at 15.12 / 15.50")
    else:
        print(f"  GS not found at {gs}: skipped")

    # --- 5. every flown mode assembles to airframe + water, and vtol_nmpc has its trim ------
    vn = open(os.path.join(controller_dir(), "px4_vtol_direct_actuator", "vtol_nmpc.py")).read()
    for kg in slosh.TANK_MODES:
        t = slosh.default_tank(water_kg=kg)
        _, _, (mk, _, _) = vs.fold_tank_into_body(cfg, t)
        want = AIRFRAME_M + kg
        ok = abs(mk - want) <= TOL_M
        has_trim = re.search(r"^\s+%s: np\.array\(\[" % re.escape(repr(kg)), vn, re.M) is not None
        print(f"  mode VTOL_TANK_KG={kg:<5}: plant {mk:.4f} kg, model {want:.4f}  {'ok' if ok else 'MISMATCH'};"
              f"  vtol_nmpc trim table {'baked' if has_trim else 'MISSING'};  {slosh.describe(t)}")
        if not ok:
            bad.append(f"mode {kg}: plant assembles to {mk:.4f}, model {want:.4f}")
        if not has_trim:
            bad.append(f"mode {kg}: vtol_nmpc.py has no baked trim table for it")

    # --- 6. THE TANK'S POSITION IS PAIRED TOO (2026-09-14) -------------------------------
    # VTOL_TANK_DX mounts the tank off the CG in the plant (vtol_utils.fsc_cad_vtol_slosh_config)
    # and the fold moves the plant's CG and inertia. The model hub folds the same variable the same
    # way (so3.CG_SHIFT), the safe controller's cg_x follows, the STESO's tank arm is about the
    # moved CG. Every offset-tank flight before this carried a 38 mm CG error the controller was
    # not told about (flight 8's hover: +1.5 N.m of pitch residual = M g x 38 mm).
    import subprocess
    py = os.path.expanduser("~/envs/isaac_env/bin/python3")
    if os.path.exists(py):
        for dx, dz in ((0.3, 0.0), (0.0, 0.15), (0.3, 0.15)):
            from dataclasses import replace as _replace
            t = slosh.default_tank()
            t = _replace(t, position=(float(c0[0]) + dx, float(c0[1]), float(c0[2]) + dz))
            _, _, (mk, ck, ik) = vs.fold_tank_into_body(cfg, t)
            env = dict(os.environ, VTOL_TANK_KG=str(slosh.tank_kg_from_env()), VTOL_TANK_DX=str(dx), VTOL_TANK_DZ=str(dz))
            r = subprocess.run([py, "-c", "import nmpc_so3_transition_node as s; print(s.CG_X, s.IXX, s.IYY, s.IZZ, s.CG_SHIFT[2])"],
                               cwd=os.path.dirname(CTRL_HUB), env=env, capture_output=True, text=True, timeout=120)
            line = [l for l in r.stdout.splitlines() if l.strip() and not l.startswith("[")]
            if not line:
                bad.append(f"could not import the hub with VTOL_TANK_DX={dx}: {r.stderr[-300:]}"); continue
            cgx, ixx, iyy, izz, sh_z = (float(v) for v in line[-1].split())
            # the plant's CG moved by (ck - c0); the hub's by CG_SHIFT
            ok = (abs((c0[0] + (cgx - 0.176)) - ck[0]) <= 1.5e-3 and abs(ixx - ik[0]) <= 3e-3
                  and abs(iyy - ik[1]) <= 3e-3 and abs(izz - ik[2]) <= 3e-3 and abs((c0[2] + sh_z) - ck[2]) <= 1.5e-3)
            print(f"  tank at (+{dx:.2f}, 0, +{dz:.2f}) m: plant CG ({ck[0]:.4f},{ck[2]:.4f}) I=({ik[0]:.3f},{ik[1]:.3f},{ik[2]:.3f}) | "
                  f"model CG_X {cgx:.4f} (dz shift {sh_z:+.4f}) I=({ixx:.3f},{iyy:.3f},{izz:.3f})  {'ok' if ok else 'MISMATCH'}")
            if not ok:
                bad.append(f"tank at ({dx}, 0, {dz}): plant CG/I ({ck[0]:.4f}, {ik}) vs model ({cgx:.4f}, ({ixx:.3f},{iyy:.3f},{izz:.3f}))")
        # the SAFE controller's cg_x must read the same variables (text pinned, like its mass)
        geo = open(os.path.join(controller_dir(), "px4_vtol_direct_actuator", "geometric_hover_node.py")).read()
        n = len(re.findall(r'0\.176 \+ float\(os\.environ\.get\("VTOL_TANK_DX", "0"\) or 0\.0\) \* float\(os\.environ\.get\("VTOL_TANK_KG", "0\.502"\) or 0\.502\) /', geo))
        print(f"  {'geometric_hover_node.py':28s} cg_x = 0.176 + VTOL_TANK_DX * VTOL_TANK_KG / M   {'ok (x%d)' % n if n >= 2 else 'MISMATCH'}")
        if n < 2:
            bad.append("geometric_hover_node.py: cg_x does not follow VTOL_TANK_DX (both the attribute and the parameter default must)")
    else:
        print(f"  {py} not found: the tank-position pairing (section 6) skipped")

    # --- 7. THE PLANT'S AERO FORCE ACTS AT THE ASSEMBLED CG (2026-09-14) ---------------------
    # The controllers' aero model has no lever arm: lift and drag act through the CG and the
    # moment is Cm alone. vtol.py's default aero centre was `body_com_offset` -- the BODY LINK's
    # CoM, 18.6 mm ahead of the assembled CG -- so 38 N of cruise lift made 0.45 N.m of nose-up
    # moment the controllers never modelled (scripts/ana_force_model.py, every bag). The default
    # is now the assembled CG of whatever config is built (the folded one for the tank aircraft).
    vsrc = open(os.path.join(HERE, "..", "extensions", "pegasus.simulator", "pegasus", "simulator",
                             "logic", "vehicles", "vtol.py")).read()
    ac_ok = re.search(r"config\.aero_center if config\.aero_center is not None\s*\n\s*else assembled_mass_properties\(config\)\[1\]", vsrc) is not None
    arm = np.asarray(cfg.body_com_offset, float) - np.asarray(c0, float)
    print(f"  vtol.py aero centre default = assembled CG ({'ok' if ac_ok else 'MISMATCH'}); "
          f"the body-link CoM it replaces sits ({1000 * arm[0]:+.1f}, {1000 * arm[2]:+.1f}) mm from it")
    if not ac_ok:
        bad.append("vtol.py: the aero force does not default to the assembled CG (the controllers' aero acts through the CG)")
    if cfg.aero_center is not None:
        bad.append(f"the airframe pins aero_center={cfg.aero_center}; the controllers model no lever arm")

    print()
    if bad:
        print(f"FAIL ({len(bad)}):")
        for b in bad:
            print("  -", b)
        return 1
    print("PASS -- plant and control model carry the same aircraft")
    return 0


if __name__ == "__main__":
    sys.exit(main())
