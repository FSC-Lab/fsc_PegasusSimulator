#!/usr/bin/env python3
"""The PLANT and the CONTROL MODEL must carry the same aircraft.

    python3 tests/test_tank_model_pairing.py

This is tank-plan phase 2's gate, and it is the one thing the plan insisted on:
the liquid goes into the plant and into `so3.M` IN THE SAME COMMIT, because the
reference is generated by solving a trim against the control model's mass. Get
them out of step and the reference stops being a trim -- the aircraft is then
tracking a package of (attitude, tilt, thrust) that does not balance, which is
exactly the failure that cost this project bags full_tr7, full_tr25 and full_tr27.

It is also the cross-repo contract test the extraction made necessary: the plant
lives here, the controller lives in fsc_autopilot_ros2, and nothing but this file
notices when they drift apart.

WHAT IS PINNED, and why it is not circular: `assembled_mass_properties` computes
the vehicle from the config's own links, and for the BASELINE airframe it
reproduces the controller's independently-derived constants exactly (M = 3.450,
CG_X = 0.1764, I = 0.265/0.303/0.490). That agreement is what makes it credible
for the tank case, where there is nothing to check against.

NOTE ON THE A/B: once this passes, the controller models the TANK aircraft. Flying
the baseline plant (`start_slosh_hil.sh --baseline`) against it means flying a
controller that believes in 0.5 kg of water that is not there. For a true baseline
run, check out the controller's `pre-slosh` tag.
"""
import ast
import importlib.util
import os
import sys
import types
from unittest import mock

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from test_slosh_import import stub_isaac, load          # noqa: E402  (one stub harness)
sys.path.insert(0, os.path.join(HERE, ".."))
from controller_path import controller_dir              # noqa: E402

CTRL_HUB = os.path.join(controller_dir(), "px4_vtol_direct_actuator",
                        "nmpc_so3_transition_node.py")
# Every OTHER copy of the vehicle mass in the controller package. so3.M is the
# model hub, but the trim generator and the SAFE controller each carry their own,
# and the 2026-09-12 audit found the generator's still at 3.45 after so3.M moved:
# a 1.245 m/s^2 vertical residual in every baked reference -- the water, exactly.
OTHER_MASS_SITES = {
    "lib/fsc_transition_ref.py":  r"\bm=([0-9.]+)",            # FSC = dict(m=..., ...)
    "geometric_hover_node.py":    r"self\.mass = ([0-9.]+)",   # safe controller default
    "vtol_nmpc.py":               r"^M = ([0-9.]+)",           # standalone node
}
TOL_M = 1e-3        # kg
TOL_CG = 1e-3       # m
TOL_I = 2e-3        # kg m^2


def controller_constants():
    """M, CG_X and the inertia diagonal, read from the controller's model hub.

    Parsed, not imported: importing it pulls casadi and builds solvers."""
    tree = ast.parse(open(CTRL_HUB).read())
    out = {}
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        # `IXX, IYY, IZZ = 0.265, 0.303, 0.490` is ONE assignment to a Tuple target,
        # not three Name targets -- miss that and the inertia silently reads as None.
        tgt = node.targets[0]
        if isinstance(tgt, ast.Tuple):
            targets = [e.id for e in tgt.elts if isinstance(e, ast.Name)]
        else:
            targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
        if isinstance(node.value, ast.Tuple):
            vals = [v.value for v in node.value.elts if isinstance(v, ast.Constant)]
            if len(targets) == len(vals):
                out.update(dict(zip(targets, vals)))
        elif isinstance(node.value, ast.Constant) and len(targets) == 1:
            out[targets[0]] = node.value.value
    return out


def main():
    bad = []
    stub_isaac()
    load("pegasus.simulator.logic.dynamics.vtol_aerodynamics", "dynamics/vtol_aerodynamics.py")
    slosh = load("pegasus.simulator.logic.dynamics.slosh", "dynamics/slosh.py")
    vtol = load("pegasus.simulator.logic.vehicles.vtol", "vehicles/vtol.py")
    vs = load("pegasus.simulator.logic.vehicles.vtol_slosh", "vehicles/vtol_slosh.py")

    cfg = vtol.quad_tiltrotor_config()
    m0, c0, i0 = vs.assembled_mass_properties(cfg)
    print(f"  plant, baseline airframe : M={m0:.3f} kg  CG=({c0[0]:.4f},{c0[1]:.4f},{c0[2]:.4f})  "
          f"I=({i0[0]:.3f},{i0[1]:.3f},{i0[2]:.3f})")

    # --- 1. the method is credible: it reproduces the controller's baseline ---
    for name, got, want, tol in (("M", m0, 3.450, TOL_M),
                                 ("CG_X", c0[0], 0.1764, TOL_CG),
                                 ("IXX", i0[0], 0.265, TOL_I),
                                 ("IYY", i0[1], 0.303, TOL_I),
                                 ("IZZ", i0[2], 0.490, TOL_I)):
        if abs(got - want) > tol:
            bad.append(f"baseline {name}: plant says {got:.4f}, the airframe's recorded "
                       f"value is {want} -- the assembly maths or the config changed")

    # --- 2. the tank aircraft ------------------------------------------------
    tank = slosh.TankConfig()
    folded, before, after = vs.fold_tank_into_body(cfg, tank)
    m1, c1, i1 = after
    print(f"  plant, WITH the tank     : M={m1:.3f} kg  CG=({c1[0]:.4f},{c1[1]:.4f},{c1[2]:.4f})  "
          f"I=({i1[0]:.3f},{i1[1]:.3f},{i1[2]:.3f})")

    exp = m0 + slosh.slosh_parameters(tank).fluid_mass
    if abs(m1 - exp) > TOL_M:
        bad.append(f"folding the tank lost mass: {m1:.4f} vs {exp:.4f}")
    # mounted at the CG -> the CG must not move at all
    moved = max(abs(c1[k] - c0[k]) for k in range(3))
    if moved > 1e-9:
        bad.append(f"the default tank moved the CG by {1000 * moved:.3f} mm; mounted at the "
                   f"assembled CG it must not move it at all")
    if not all(i1[k] >= i0[k] for k in range(3)):
        bad.append("adding mass reduced an inertia")
    # the caller's config must not have been mutated
    if cfg.mass != 2.95:
        bad.append(f"fold_tank_into_body MUTATED the caller's config (mass now {cfg.mass})")

    # --- 3. THE PAIRING ------------------------------------------------------
    k = controller_constants()
    cm, ccg = k.get("M"), k.get("CG_X")
    ci = (k.get("IXX"), k.get("IYY"), k.get("IZZ"))
    print(f"  control model            : M={cm} kg  CG_X={ccg}  I={ci}")
    if cm is None or ccg is None or None in ci:
        bad.append(f"could not read M/CG_X/I* from {CTRL_HUB}")
    else:
        if abs(cm - m1) > TOL_M:
            bad.append(f"MASS MISMATCH: the plant flies {m1:.3f} kg with the tank, the control "
                       f"model carries {cm} kg. Update M in {os.path.basename(CTRL_HUB)} "
                       f"(and expect a JIT rebuild -- the cache key hashes the model source). "
                       f"Until then the reference is not a trim.")
        if abs(ccg - c1[0]) > TOL_CG:
            bad.append(f"CG MISMATCH: plant {c1[0]:.4f} m, control model {ccg} m")
        for nm, got, want in zip(("IXX", "IYY", "IZZ"), ci, i1):
            if abs(got - want) > TOL_I:
                bad.append(f"{nm} MISMATCH: plant {want:.4f}, control model {got}")

    # --- 4. the other copies of the mass must agree with the hub -----------
    import re
    for rel, pat in OTHER_MASS_SITES.items():
        path = os.path.join(controller_dir(), "px4_vtol_direct_actuator", rel)
        src = open(path).read()
        hit = re.search(pat, src, re.M)
        if not hit:
            bad.append(f"could not find the mass in {rel} with /{pat}/")
            continue
        val = float(hit.group(1))
        tag = "ok" if abs(val - m1) <= TOL_M else "MISMATCH"
        print(f"  {rel:28s} mass={val:<10} {tag}")
        if tag != "ok":
            bad.append(f"{rel} carries mass {val}; the aircraft is {m1:.4f} kg -- a stale copy "
                       f"(the trim generator's copy left a 1.245 m/s^2 residual once)")

    print()
    if bad:
        print(f"FAIL ({len(bad)}):")
        for b in bad:
            print("  -", b)
        return 1
    print("PASS -- plant and control model carry the same aircraft")
    return 0


if __name__ == "__main__":
    sys.exit(main())
