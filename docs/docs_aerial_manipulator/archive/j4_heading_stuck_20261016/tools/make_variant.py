#!/usr/bin/env python3
"""The Isaac variant of the 2026-10-16 j4 fix: the sim pick-and-drop yaml as regenerated with the fix
(wb_ky_psi / wb_dy_psi 2.5 / 0.93 + wb_l1_stuck_hold_j4, from the mirror), plus pick_place_drop_auto false --
the one change the lift_lurch_gains_20261016 baseline flights (variant D = today's shipped config before the
fix) also carried, so the mission driver times every release the same way.
    /usr/bin/python3 make_variant.py   -> ../variants/J.yaml"""
import os
import re
CFG = os.path.expanduser("~/ros2_ws/src/fsc_autopilot_ros2/config")
SRC = os.path.join(CFG, "params_single_aerial_manipulator_whole_body_l1_4d_direct_actuation_t650_sim_pick_and_drop.yaml")
out = open(SRC).read()
for k in ("wb_ky_psi: 2.5", "wb_dy_psi: 0.93", "wb_l1_stuck_hold_j4: true", "wb_k_r: 2.134", "wb_k_w: 1.567"):
    if not re.search(rf"^    {re.escape(k)}\b", out, flags=re.M):
        raise SystemExit(f"the sim pick-and-drop yaml does not carry {k} -- regenerate it first")
pat = r"^(    pick_place_drop_auto:[ \t]*)([^#\n]*?)([ \t]*(#.*)?)$"
if len(re.findall(pat, out, flags=re.M)) != 1:
    raise SystemExit("pick_place_drop_auto not found exactly once")
out = re.sub(pat, lambda m: f"{m.group(1)}false  # J4 FIX ISAAC VARIANT (was {m.group(2).strip()})", out, flags=re.M)
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "variants", "J.yaml")
open(path, "w").write(f"# GENERATED by j4_heading_stuck_20261016/tools/make_variant.py from {os.path.basename(SRC)}\n" + out)
print("wrote", os.path.abspath(path))
