#!/usr/bin/env python3
"""The four controller variants of the 2026-10-16 lift/release-lurch test, from the sim pick-and-drop yaml
(..._l1_4d_direct_actuation_t650_sim_pick_and_drop.yaml, itself generated from the mirror):

  A  today's          wb_l1_omega_c_r 0.7428, wb_k_r / wb_k_w 1.6 / 1.2
  B  faster rotation  wb_l1_omega_c_r 1.0
  C  faster rotation  wb_l1_omega_c_r 1.25
  D  free-flight attitude gains  wb_k_r / wb_k_w 2.134 / 1.567 (H1b), omega_c_r 0.7428

and in every variant pick_place_drop_auto false: the mission driver times the release (its 2 s dwell)
the same way in all of them, and the arm GS -- which runs in these headless flights -- must not open the
gripper on its own. Nothing else changes (checked: each key replaced exactly once).

    /usr/bin/python3 make_variants.py
"""
import os
import re

CFG = os.path.expanduser("~/ros2_ws/src/fsc_autopilot_ros2/config")
SRC = os.path.join(CFG, "params_single_aerial_manipulator_whole_body_l1_4d_direct_actuation_t650_sim_pick_and_drop.yaml")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "variants")
VARIANTS = {
    "A": {},
    "B": {"wb_l1_omega_c_r": "1.0"},
    "C": {"wb_l1_omega_c_r": "1.25"},
    "D": {"wb_k_r": "2.134", "wb_k_w": "1.567"},
}
COMMON = {"pick_place_drop_auto": "false"}

src = open(SRC).read()
for name, ov in VARIANTS.items():
    out = src
    for k, v in {**ov, **COMMON}.items():
        pat = rf"^(    {re.escape(k)}:[ \t]*)([^#\n]*?)([ \t]*(#.*)?)$"
        if len(re.findall(pat, out, flags=re.M)) != 1:
            raise SystemExit(f"{name}: {k} not found exactly once")
        out = re.sub(pat, lambda m: f"{m.group(1)}{v}  # LURCH TEST VARIANT {name} (was {m.group(2).strip()})",
                     out, flags=re.M)
    path = os.path.join(OUT, f"{name}.yaml")
    open(path, "w").write(f"# GENERATED by lift_lurch_gains_20261016/tools/make_variants.py from {os.path.basename(SRC)}\n" + out)
    print(f"{name}: {', '.join(f'{k} {v}' for k, v in {**ov, **COMMON}.items())} -> {path}")
